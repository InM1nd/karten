UPM = 2400
WEIGHTS = {"": 1.6, "_b": 2.2}  # regular + bold stroke (in 24-grid units)

def glyph(defs, stroke):
    out = pathops.Path()
    for d in defs:
        p = pathops.Path()
        parse_path(d, TransformPen(p.getPen(), (100, 0, 0, -100, 0, UPM)))
        p.stroke(stroke * 100, pathops.LineCap.ROUND_CAP, pathops.LineJoin.ROUND_JOIN, 4)
        p.convertConicsToQuads(0.5)
        out.addPath(p)
    out = pathops.simplify(out, clockwise=True)
    pen = TTGlyphPen(None)
    out.draw(Cu2QuPen(pen, max_err=2, reverse_direction=False))
    return pen.glyph()

order, cmap, glyphs, metrics, ts = [".notdef"], {}, {}, {}, {}
empty = TTGlyphPen(None); glyphs[".notdef"] = empty.glyph(); metrics[".notdef"] = (UPM, 0)
for wi, (suffix, sw) in enumerate(WEIGHTS.items()):
    for i, (name, defs) in enumerate(ICONS.items()):
        gname = name + suffix
        cp = 0xE000 + wi * 0x40 + i
        order.append(gname); cmap[cp] = gname
        g = glyphs[gname] = glyph(defs, sw)
        metrics[gname] = (UPM, 0)
        ts.setdefault(name, [0, 0])[wi] = cp

fb = FontBuilder(UPM, isTTF=True)
fb.setupGlyphOrder(order)
fb.setupCharacterMap(cmap)
fb.setupGlyf(glyphs)
for n, g in glyphs.items():
    g.recalcBounds(fb.font["glyf"])
    metrics[n] = (UPM, getattr(g, "xMin", 0) or 0)
fb.setupHorizontalMetrics(metrics)
fb.setupHorizontalHeader(ascent=UPM, descent=0, lineGap=0)
fb.setupNameTable({"familyName": "KartenIcons", "styleName": "Regular", "copyright": "Icons: Lucide (ISC). Karten."})
fb.setupOS2(sTypoAscender=UPM, sTypoDescender=0, sTypoLineGap=0, usWinAscent=UPM, usWinDescent=0, fsType=0)
fb.setupPost()
fb.save("assets/fonts/KartenIcons.ttf")

